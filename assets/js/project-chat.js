// ─────────────────────────────────────────────────────────────────────────────
// SETUP REQUIRED BEFORE THIS WORKS END-TO-END:
//
// 1. Deploy the Cloudflare Worker at cloudflare-worker/index.js and set:
//    const WORKER_URL = 'https://your-worker.your-subdomain.workers.dev';
//
// 2. Create a free Formspree form at formspree.io, then set:
//    const FORMSPREE_ENDPOINT = 'https://formspree.io/f/YOUR_FORM_ID';
//
// Until those are set, the panel opens, chats work, but AI answers are
// replaced with a "not yet connected" message, and emails won't send.
// ─────────────────────────────────────────────────────────────────────────────

const WORKER_URL       = '';  // TODO: paste your Cloudflare Worker URL here
const FORMSPREE_ENDPOINT = ''; // TODO: paste your Formspree endpoint here

(function () {
  // ── Project content index ────────────────────────────────────────────────
  // Grounding text is loaded from /assets/data/<slug>.json (generated by
  // scripts/extract-content.mjs once you unlock the case studies).
  // If no data file exists yet, the agent says so gracefully.
  const contentCache = {};

  async function loadContent(slug) {
    if (contentCache[slug] !== undefined) return contentCache[slug];
    try {
      const res = await fetch(`/assets/data/${slug}.json`);
      if (!res.ok) throw new Error('not found');
      contentCache[slug] = await res.json();
    } catch {
      contentCache[slug] = null;
    }
    return contentCache[slug];
  }

  // ── Panel state ──────────────────────────────────────────────────────────
  let activeSlug  = null;
  let activeTitle = null;
  let awaitingEmail = false;
  let history = [];

  const backdrop  = document.getElementById('lw-panel-overlay');
  const popup     = document.getElementById('lw-panel');
  const titleEl   = document.getElementById('lw-panel-title');
  const messages  = document.getElementById('lw-panel-messages');
  const input     = document.getElementById('lw-panel-input');
  const sendBtn   = document.getElementById('lw-panel-send');
  const closeBtn  = document.getElementById('lw-panel-close');

  // ── Open / close ─────────────────────────────────────────────────────────
  function openPanel(slug, title, triggerEl) {
    activeSlug  = slug;
    activeTitle = title;
    awaitingEmail = false;
    history = [];
    messages.innerHTML = '';
    titleEl.textContent = title;

    // Position popup near the trigger tile
    positionPopup(triggerEl);

    backdrop.style.display = 'block';
    popup.style.display    = 'flex';
    input.focus();

    addBubble(`Hi! I can answer questions about the <strong>${escapeHtml(title)}</strong> case study. What would you like to know?`, 'agent');
    loadContent(slug);
  }

  function positionPopup(triggerEl) {
    const tile = triggerEl.closest('.work-item');
    const rect = tile.getBoundingClientRect();
    const PW = 320, PH = 420, GAP = 12;

    let top  = rect.top  - PH - GAP;
    let left = rect.left + rect.width / 2 - PW / 2;

    // Flip below if not enough room above
    if (top < GAP) top = rect.bottom + GAP;
    // Clamp horizontal
    left = Math.max(GAP, Math.min(left, window.innerWidth - PW - GAP));
    // Clamp vertical
    top  = Math.max(GAP, Math.min(top,  window.innerHeight - PH - GAP));

    popup.style.top  = top  + 'px';
    popup.style.left = left + 'px';
  }

  function closePanel() {
    backdrop.style.display = 'none';
    popup.style.display    = 'none';
    activeSlug = null;
  }

  // ── Bubble helpers ────────────────────────────────────────────────────────
  function addBubble(html, role) {
    const row = document.createElement('div');
    row.className = 'msg ' + role;
    if (role === 'agent') {
      row.innerHTML = `
        <div class="agent-avatar">
          <img src="/assets/65e88c6319801815fa38ea12_lw_logo.png" alt="LW" width="16"/>
        </div>
        <div class="bubble">${html}</div>`;
    } else {
      row.innerHTML = `<div class="bubble">${escapeHtml(html)}</div>`;
    }
    messages.appendChild(row);
    row.scrollIntoView({ behavior: 'smooth', block: 'end' });
    return row;
  }

  function addTyping() {
    const row = document.createElement('div');
    row.className = 'msg agent';
    row.innerHTML = `
      <div class="agent-avatar">
        <img src="/assets/65e88c6319801815fa38ea12_lw_logo.png" alt="LW" width="16"/>
      </div>
      <div class="bubble typing"><span></span><span></span><span></span></div>`;
    messages.appendChild(row);
    row.scrollIntoView({ behavior: 'smooth', block: 'end' });
    return row;
  }

  function setEnabled(on) {
    input.disabled  = !on;
    sendBtn.disabled = !on;
    if (on) input.focus();
  }

  // ── Ask Claude (grounded) ─────────────────────────────────────────────────
  async function askClaude(question, content) {
    if (!WORKER_URL) return null; // not yet deployed

    const systemPrompt = content
      ? `You are an assistant that answers questions strictly based on the following case study text. Never invent information, never cite external sources. If the answer isn't in the text, say so honestly. Be conversational, not robotic — paraphrase rather than quote verbatim. Keep answers concise (2-4 sentences unless more detail is truly needed).\n\n---\n${content.text}\n---`
      : `You are an assistant for a portfolio case study called "${activeTitle}". The case study content hasn't been indexed yet — let the user know politely.`;

    const body = {
      system: systemPrompt,
      messages: [...history, { role: 'user', content: question }]
    };

    try {
      const res  = await fetch(WORKER_URL, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(body)
      });
      if (!res.ok) throw new Error('worker error');
      const data = await res.json();
      return data.content?.[0]?.text || null;
    } catch {
      return null;
    }
  }

  // ── Formspree: email collection ───────────────────────────────────────────
  async function sendToFormspree(question, email) {
    if (!FORMSPREE_ENDPOINT) return;
    try {
      await fetch(FORMSPREE_ENDPOINT, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          project:  activeTitle,
          question: question,
          email:    email || '(not provided)'
        })
      });
    } catch { /* silent */ }
  }

  // ── Main submit handler ───────────────────────────────────────────────────
  async function handleSubmit() {
    const text = input.value.trim();
    if (!text || !activeSlug) return;

    input.value = '';
    setEnabled(false);
    addBubble(text, 'user');

    // Email collection mode
    if (awaitingEmail) {
      awaitingEmail = false;
      const isEmail = /\S+@\S+\.\S+/.test(text);
      const email   = isEmail ? text : null;

      // Log the unanswered question + email regardless
      const unansweredQ = history.length
        ? history[history.length - 1]?.content
        : '(unknown)';
      await sendToFormspree(unansweredQ, email);

      if (email) {
        addBubble("Got it — Lauren will be in touch. Thanks for your curiosity :)", 'agent');
      } else {
        addBubble("No worries — I've let Lauren know. She may cover it in the case study soon.", 'agent');
      }
      setEnabled(true);
      return;
    }

    const typing  = addTyping();
    const content = await loadContent(activeSlug);

    // Push to conversation history for multi-turn context
    history.push({ role: 'user', content: text });

    let answer = null;
    if (WORKER_URL) {
      answer = await askClaude(text, content);
    }

    typing.remove();

    if (answer) {
      addBubble(escapeHtml(answer), 'agent');
      history.push({ role: 'assistant', content: answer });
    } else if (!WORKER_URL) {
      // Worker not yet deployed — explain gracefully
      addBubble("The AI backend isn't connected yet — check back soon, or <a href=\"/works/${activeSlug}\">read the full case study</a> in the meantime.", 'agent');
    } else {
      // Worker returned nothing / couldn't answer from content
      addBubble(`Lauren hasn't covered that specifically in this case study. She'll be notified you asked. Would you like to leave your email so she can follow up directly?`, 'agent');
      history.push({ role: 'assistant', content: "Lauren hasn't covered that in this case study." });
      awaitingEmail = true;
    }

    setEnabled(true);
  }

  // ── Event wiring ──────────────────────────────────────────────────────────
  document.querySelectorAll('.lw-ask-btn').forEach(btn => {
    btn.addEventListener('click', e => {
      e.preventDefault();
      e.stopPropagation();
      openPanel(btn.dataset.slug, btn.dataset.title, btn);
    });
  });

  closeBtn.addEventListener('click', closePanel);
  backdrop.addEventListener('click', closePanel);
  sendBtn.addEventListener('click', handleSubmit);
  input.addEventListener('keydown', e => {
    if (e.key === 'Enter' && !e.shiftKey) { e.preventDefault(); handleSubmit(); }
  });
  document.addEventListener('keydown', e => {
    if (e.key === 'Escape' && popup.style.display !== 'none') closePanel();
  });

  function escapeHtml(str) {
    return str.replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;').replace(/"/g,'&quot;');
  }
})();
